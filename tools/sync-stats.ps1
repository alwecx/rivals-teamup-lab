<#
  sync-stats.ps1 - snapshot every hero's official numbers into
  data/official-stats.js for the simulator (sim.html).

  Reads https://www.marvelrivals.com/heroes/<id>/index.html for each hero on the
  official heroes index and keeps, verbatim:
    * variants: name + stats (HEALTH, MOVEMENT SPEED, ...)
    * skills:   name, key, type, description, stats [label, value]
    * teamups:  name, key, description, base/enhanced stats
  The simulator's hand-written combat models (data/sim/*.js) cite these numbers;
  re-run this after a patch and diff the output to see what moved.

  Usage (repo root):  powershell -ExecutionPolicy Bypass -File tools\sync-stats.ps1
#>
param(
  [string]$Out = (Join-Path $PSScriptRoot '..\data\official-stats.js'),
  [string]$Html = (Join-Path $PSScriptRoot '..\index.html')
)
$ErrorActionPreference = 'Stop'
$UA = 'rivals-teamup-lab/1.0 (stats sync script)'
$Base = 'https://www.marvelrivals.com/heroes'

function Get-Page([string]$url) {
  $r = Invoke-WebRequest -Uri $url -UserAgent $UA -UseBasicParsing
  [Text.Encoding]::UTF8.GetString($r.RawContentStream.ToArray())
}
function Key([string]$s) { ($s.ToLowerInvariant() -replace '[^a-z0-9]', '') }
function TitleCase([string]$s) {
  $small = 'a','an','and','of','the','to','in','on','with'
  $w = $s.ToLowerInvariant() -split ' '
  for ($i = 0; $i -lt $w.Count; $i++) { if ($i -gt 0 -and $small -contains $w[$i]) { continue }; if ($w[$i]) { $w[$i] = $w[$i].Substring(0,1).ToUpperInvariant() + $w[$i].Substring(1) } }
  $w -join ' '
}
function Stats($arr) {
  $l = New-Object System.Collections.ArrayList
  foreach ($s in @($arr)) { if ($null -ne $s) { [void]$l.Add(@([string]$s.label, (([string]$s.value + ' ' + [string]$s.unit).Trim()))) } }
  , $l   # leading comma: keep a 1-item list from being unrolled into a flat pair
}
function JsStr([string]$s) { '"' + ($s -replace '\\', '\\' -replace '"', '\"' -replace "`r?`n", '\n') + '"' }
function ToJs($v, [int]$ind = 0) {
  $pad = ' ' * $ind
  if ($null -eq $v) { return 'null' }
  if ($v -is [string]) { return JsStr $v }
  if ($v -is [bool]) { return $v.ToString().ToLower() }
  if ($v -is [int] -or $v -is [double]) { return [string]$v }
  if ($v -is [Collections.IDictionary]) {
    $parts = foreach ($k in $v.Keys) { "$pad  " + (JsStr $k) + ':' + (ToJs $v[$k] ($ind + 2)) }
    return "{`n" + ($parts -join ",`n") + "`n$pad}"
  }
  if ($v -is [Collections.IEnumerable]) {
    $items = @($v)
    if (-not $items.Count) { return '[]' }
    # short scalar arrays (stat pairs) stay on one line
    if (-not ($items | Where-Object { $_ -is [Collections.IDictionary] })) { return '[' + (($items | ForEach-Object { ToJs $_ 0 }) -join ',') + ']' }
    return "[`n" + (($items | ForEach-Object { "$pad  " + (ToJs $_ ($ind + 2)) }) -join ",`n") + "`n$pad]"
  }
  JsStr ([string]$v)
}

# display names from the team-up lab's RAW table
$raw = [IO.File]::ReadAllText((Resolve-Path $Html))
$names = @{}
[regex]::Matches($raw, '(?m)^\["((?:[^"\\]|\\.)+)",[VDS],') | ForEach-Object { $names[(Key $_.Groups[1].Value)] = $_.Groups[1].Value }

$index = Get-Page "$Base/index.html"
$build = [regex]::Match($index, '/pc/gw/(\d{14})/').Groups[1].Value
$site = [regex]::Matches($index, 'data-id="([a-z0-9]+)" data-name="([^"]+)"') |
  ForEach-Object { [pscustomobject]@{ id=$_.Groups[1].Value; nick=[Net.WebUtility]::HtmlDecode($_.Groups[2].Value) } } |
  Sort-Object id -Unique

$heroes = [ordered]@{}
foreach ($s in ($site | Sort-Object nick)) {
  $page = Get-Page "$Base/$($s.id)/index.html"
  $m = [regex]::Match($page, '(?s)window\.__HERO_DATA__\s*=\s*(\{.*?\})\s*;?\s*</script>')
  if (-not $m.Success) { Write-Warning "$($s.nick): no data"; continue }
  $d = ConvertFrom-Json $m.Groups[1].Value
  $name = if ($names.ContainsKey((Key $s.nick))) { $names[(Key $s.nick)] } else { TitleCase $s.nick }
  $h = [ordered]@{
    id = $s.id
    roles = @($d.jobs | ForEach-Object { TitleCase ([string]$_) })
    variants = @($d.variants | ForEach-Object { [ordered]@{ name = [string]$_.name; stats = (Stats $_.stats) } })
    skills = @($d.skills | ForEach-Object { [ordered]@{ name = [string]$_.name; key = [string]$_.key; type = [string]$_.type; desc = [string]$_.description; stats = (Stats $_.stats) } })
    teamups = @($d.teamups | ForEach-Object {
      $tb = @($_.tiers | Where-Object { $_.tier -eq 'base' })[0]; $te = @($_.tiers | Where-Object { $_.tier -eq 'enhanced' })[0]
      [ordered]@{ name = [string]$_.name; key = [string]$_.key; desc = [string]$(if ($tb) { $tb.description } else { '' }); base = (Stats $tb.stats); enhanced = (Stats $te.stats) } })
  }
  $heroes[$name] = $h
  Write-Host "$name  ($(@($d.skills).Count) skills)"
}
$doc = [ordered]@{ source = "$Base/index.html"; build = $build; synced = (Get-Date -Format 'yyyy-MM-dd'); heroes = $heroes }
$js = "/* Generated by tools/sync-stats.ps1 - official Marvel Rivals hero numbers, verbatim. Do not edit by hand. */`nwindow.OFFICIAL_STATS = " + (ToJs $doc) + ";`n"
New-Item -ItemType Directory -Force (Split-Path $Out) | Out-Null
[IO.File]::WriteAllText([IO.Path]::GetFullPath($Out), $js, (New-Object Text.UTF8Encoding $false))
Write-Host "Wrote $($heroes.Count) heroes (build $build) to $Out"
